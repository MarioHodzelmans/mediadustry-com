import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";

// Keep the source template intact. Public pages receive only their used rules;
// legacy examples request the original complete stylesheet when visited.
const roots = [
  "app/layout.tsx",
  "app/werk/[slug]/page.tsx",
  "app/work/page.tsx",
  "app/work/[slug]/page.tsx",
  "components/home/RealWorkHome.tsx",
  "components/footers/NativeFooter3.tsx",
];
for (const dir of ["components/headers", "components/showcase"]) {
  for (const file of await readdir(dir))
    if (/\.(tsx|css)$/.test(file)) roots.push(`${dir}/${file}`);
}
const visited = new Set();
const tokens = new Set([
  "light",
  "dark",
  "no-touch",
  "touch",
  "menu-open",
  "is-hidden",
  "is-visible",
  "open",
  "hidden",
  "active",
  "md-skip-link",
]);
async function collect(file) {
  if (visited.has(file)) return;
  visited.add(file);
  let source;
  try {
    source = await readFile(file, "utf8");
  } catch {
    return;
  }
  for (const token of source.match(/[A-Za-z_][A-Za-z0-9_-]*/g) ?? [])
    tokens.add(token);
  // Component dependencies contribute their literal DOM classes, not libraries.
  for (const match of source.matchAll(
    /(?:from\s+|import\s*)["'](@\/[^"']+|\.\.?\/[^"']+)["']/g,
  )) {
    const target = match[1].startsWith("@/")
      ? match[1].slice(2)
      : path.join(path.dirname(file), match[1]);
    if (!target.endsWith(".css"))
      await collect(target.endsWith(".tsx") ? target : `${target}.tsx`);
  }
}
await Promise.all(roots.map(collect));
const template = (await readFile("styles/template.css", "utf8")).replace(
  /^@import[^;]+;\s*/gm,
  "",
);
const menu = await readFile("styles/menu-open.css", "utf8");
const sources = await Promise.all(
  ["loader", "plugins", "main"].map((name) =>
    readFile(`public/css/${name}.css`, "utf8"),
  ),
);
const combined = sources.join("\n") + "\n" + template + "\n" + menu;
const tree = postcss.parse(combined);
tree.walkComments((node) => {
  if (!node.text.startsWith("!")) node.remove();
});
tree.walkRules((rule) => {
  if (rule.parent.type === "atrule" && /keyframes$/i.test(rule.parent.name))
    return;
  const selectors = rule.selectors.filter((selector) => {
    const classes = [...selector.matchAll(/\.([A-Za-z_][A-Za-z0-9_-]*)/g)].map(
      (match) => match[1],
    );
    return classes.every((name) => tokens.has(name));
  });
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
tree.walkAtRules((at) => {
  if (at.nodes && !at.nodes.length) at.remove();
});
// Public CSS has a different directory than the original css assets.
tree.walkDecls((decl) => {
  decl.value = decl.value.replace(
    /url\((['"]?)\.\.\/([^)'"\s]+)\1\)/g,
    'url("/$2")',
  );
});
const improvements = `
/* Shared native shell: accessible focus, narrow devices, no layout-hiding animation. */
body { min-width: 0; }
#site-content { outline: none; }
.md-skip-link { position:fixed;left:2rem;top:1rem;z-index:1000;padding:1rem 1.5rem;background:var(--base);color:var(--t-bright);transform:translateY(-200%);font-size:1.6rem; }
.md-skip-link:focus { transform:translateY(0); }
html :focus-visible { outline:2px solid var(--t-bright) !important;outline-offset:5px; }
@media(prefers-reduced-motion:no-preference) { html { scroll-behavior:smooth; } }
@media(prefers-reduced-motion:reduce) { *,*::before,*::after { scroll-behavior:auto!important; } }
`;
await writeFile(
  "styles/site-core.css",
  "/* Generated by scripts/build-site-styles.mjs from the original template. */\n" +
    tree.toString() +
    improvements,
);
const lenis = await readFile("node_modules/lenis/dist/lenis.css", "utf8");
await writeFile(
  "public/css/legacy-template.css",
  '/* Full styles, loaded only on the original template examples. */\n@import url("/css/loader.css");\n@import url("/css/plugins.css");\n@import url("/css/main.css");\n' +
    lenis +
    "\n" +
    template +
    "\n" +
    menu,
);
console.log(
  `Native CSS: ${Buffer.byteLength(tree.toString() + improvements)} bytes (source ${Buffer.byteLength(combined)} bytes).`,
);
